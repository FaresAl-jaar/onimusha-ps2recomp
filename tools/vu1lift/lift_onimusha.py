#!/usr/bin/env python3
"""Lift the VU1 micro images Onimusha: Dawn of Dreams runs to C++ (one function per image).

Input is a PS2X_VU1_CENSUS directory (manifest.json, gitaroo_census.json and the vu1_<hash>.bin
images). Every image with enough cycles is lifted with vu1lift.Lifter (Gitaroo Man Native's lifter,
MIT). Roots are the census entries, every executed pair right after an E bit's delay slot (where
MSCNT resumes) and the JR/JALR targets the census saw for that image.

Usage: python3 tools/vu1lift/lift_onimusha.py --census /tmp/census [--min-share 0.01]
                                              [-o ps2xRuntime/src/lib/vu/generated/ps2_vu1_lifted_onimusha.inc]
"""
import argparse
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vu1lift  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def lift_image(index, image_bytes, entries, jr_targets, executed, exact_flags):
    cfg = {"entries": ["%x" % e for e in sorted(entries)],
           "jr_targets": ["%x" % t for t in sorted(jr_targets)],
           "dynamic_branches": {},
           "executed": sorted(executed)}
    lifter = vu1lift.Lifter(image_bytes, cfg)
    text = lifter.emit(exact_flags)
    head, sep, body = text.partition("int VU1Lifted::runProgram(VU1Interpreter &vu, LiftedRun &run, uint32_t startPc)")
    if not sep:
        raise SystemExit("unexpected lifter output")
    out = ["namespace onimusha_vu1_%d" % index, "{", head, "}", "",
           "template <>",
           "int VU1Lifted::runImage<%d>(VU1Interpreter &vu, LiftedRun &run, uint32_t startPc)" % index + body]
    reach = {pc for b in lifter.blocks.values() for pc in b[0]}
    return "\n".join(out), lifter, len(reach)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--census", required=True)
    ap.add_argument("--min-share", type=float, default=0.01,
                    help="lift images with at least this share of all VU1 cycles")
    ap.add_argument("--exact-flags", action="store_true")
    ap.add_argument("-o", "--output", default=os.path.join(
        REPO, "ps2xRuntime/src/lib/vu/generated/ps2_vu1_lifted_onimusha.inc"))
    args = ap.parse_args(argv)

    manifest = json.load(open(os.path.join(args.census, "manifest.json")))
    census = json.load(open(os.path.join(args.census, "gitaroo_census.json")))
    by_hash = {im["crc"]: im for im in census["images"]}
    jumps = {}
    for h, pc, target, _ in census.get("image_jumps", []):
        jumps.setdefault(h, set()).add(target)
    total = sum(im["cycles"] for im in census["images"]) or 1

    parts, table = [], []
    for prog in sorted(manifest["programs"], key=lambda p: -by_hash[p["crc"]]["cycles"]):
        h = prog["crc"]
        im = by_hash[h]
        share = im["cycles"] / total
        if share < args.min_share:
            continue
        data = open(os.path.join(args.census, prog["image"]), "rb").read()
        code_hi = (prog["code_hi"] + 7) & ~7
        image = data[:code_hi]
        executed = {int(k) for k in im["pc_count"]}
        entries = {int(k) for k in im["entries"]}
        for pc in range(0, len(image), 8):
            lo, up = struct.unpack_from("<II", image, pc)
            if up & 0x40000000 and pc + 16 in executed:
                entries.add(pc + 16)
        index = len(table)
        try:
            text, lifter, reach = lift_image(index, image, entries, jumps.get(h, set()), executed, args.exact_flags)
        except SystemExit as e:
            print("image %s (%.1f%% of cycles) skipped: %s" % (h, share * 100, e))
            continue
        parts.append("// ---- image %s: %.1f%% of VU1 cycles, %d bytes, %d blocks, %d pairs reachable ----\n%s"
                     % (h, share * 100, len(image), len(lifter.blocks), reach, text))
        table.append((index, h, lifter.flags_exact))
        print("image %s: %.1f%% of cycles, %d entries, %d blocks, %d pairs reachable"
              % (h, share * 100, len(entries), len(lifter.blocks), reach))

    lines = ["// Generated by tools/vu1lift/lift_onimusha.py from a PS2X_VU1_CENSUS run. Do not edit.",
             "// Included at file scope by ps2_vu1_lifted.cpp, after the VU1Lifted helpers.", ""]
    lines += parts
    lines.append("")
    lines.append("static const VU1Lifted::Image kLiftedImages[] = {")
    for index, h, exact in table:
        ns = "onimusha_vu1_%d" % index
        lines.append("    {%s::kImage, %s::kImageBytes, %s::isBlockStart, &VU1Lifted::runImage<%d>, %s, \"%s\"},"
                     % (ns, ns, ns, index, "true" if exact else "false", h))
    lines.append("};")
    lines.append("constexpr uint32_t kLiftedImageCount = %d;" % len(table))
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d images)" % (args.output, len(table)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
